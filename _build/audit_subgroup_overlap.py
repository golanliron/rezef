# קומפילציה
COMPILED = {cat: [(lbl, re.compile(pat)) for lbl, pat in groups] for cat, groups in SUB_GROUPS.items()}

# בדיקת חפיפות לכל קטגוריה
print("="*70)
print("בדיקת קבוצות-משנה: רשומות שמתאימות ליותר מקבוצה אחת")
print("="*70)

for cat, groups in COMPILED.items():
    records = [d for d in data if d.get('c') == cat]
    if not records:
        continue
    print(f"\n── {cat} ({len(records)} רשומות) ──")

    # ספירה: כמה רשומות מתאימות לכל קבוצה (count) vs first-match-wins (assigned)
    matched_count = {lbl: 0 for lbl, _ in groups}
    assigned_count = {lbl: 0 for lbl, _ in groups}
    other_count = 0
    overlaps_count = 0
    overlap_examples = {}  # (a, b) → [names]

    for d in records:
        text = (d.get('s') or '') + ' ' + (d.get('n') or '') + ' ' + (d.get('d') or '')
        matches = [lbl for lbl, pat in groups if pat.search(text)]
        if not matches:
            other_count += 1
            continue
        for lbl in matches:
            matched_count[lbl] += 1
        # first match wins
        assigned_count[matches[0]] += 1
        if len(matches) > 1:
            overlaps_count += 1
            # תיעוד הצמדים
            for i in range(len(matches)):
                for j in range(i+1, len(matches)):
                    pair = (matches[i], matches[j])
                    overlap_examples.setdefault(pair, []).append(d.get('n', '?'))

    # סיכום
    total_no_other = len(records) - other_count
    print(f"  רשומות עם חפיפה: {overlaps_count}/{total_no_other} ({100*overlaps_count/max(total_no_other,1):.0f}%)")
    if other_count:
        print(f"  ללא התאמה ('אחר'): {other_count}")

    # הצג קבוצות שיש להן הבדל גדול בין count ל-assigned
    print("\n  קבוצה                          | match | first-win | הפרש")
    print("  " + "-"*65)
    for lbl, _ in groups:
        m = matched_count[lbl]
        a = assigned_count[lbl]
        diff = m - a
        marker = " ⚠" if diff >= 5 else ("  " if diff == 0 else "  ")
        print(f"  {lbl:30s} | {m:5d} | {a:9d} |{marker}{diff:+d}")

    # הצג צמדי חפיפה גדולים
    if overlap_examples:
        big_overlaps = sorted(overlap_examples.items(), key=lambda x: -len(x[1]))[:3]
        if big_overlaps and len(big_overlaps[0][1]) >= 3:
            print("\n  שיעורי חפיפה מובילים:")
            for (a, b), names in big_overlaps:
                if len(names) < 3:
                    continue
                print(f"    {a} ↔ {b}: {len(names)} רשומות")
                for n in names[:3]:
                    print(f"      • {n[:55]}")
